"""
RBAC authentication and authorization helpers.

Tokens are signed HS256 JWTs generated by the server on login.
The secret is read from JWT_SECRET_KEY in the environment.
Roles are NEVER trusted from request bodies or query strings —
only from the verified token payload (which is derived from the DB row).
"""

import datetime
import functools
import os
from typing import Any

import jwt
from flask import jsonify, request, g
from postgrest import APIError


# ---------------------------------------------------------------------------
# Permission map  (role → frozenset of permission strings)
# ---------------------------------------------------------------------------
PERMISSIONS: dict[str, frozenset] = {
    "administrator": frozenset([
        "users:read", "users:write", "users:delete",
        "roles:assign",
        "events:read", "events:write", "events:delete", "events:publish",
        "registrations:read_all", "registrations:approve",
        "analytics:read",
        "settings:write",
        "audit:read",
    ]),
    "organizer": frozenset([
        "events:read", "events:write_own",
        "registrations:read_own_event",
        "analytics:read_own",
    ]),
    "student": frozenset([
        "events:read",
        "registrations:read_own", "registrations:create", "registrations:cancel_own",
        "profile:read_own", "profile:write_own",
    ]),
}

ROLE_ALIASES = {"admin": "administrator"}


def _normalise_role(role: str) -> str:
    r = str(role or "student").strip().lower()
    return ROLE_ALIASES.get(r, r)


# ---------------------------------------------------------------------------
# JWT helpers
# ---------------------------------------------------------------------------
def _jwt_secret() -> str:
    secret = os.environ.get("JWT_SECRET_KEY", "")
    if not secret:
        raise RuntimeError("JWT_SECRET_KEY environment variable is not set")
    return secret


def create_token(user: dict) -> str:
    """Issue a signed JWT for a resolved user dict (id, email, role)."""
    role = _normalise_role(user.get("role", "student"))
    now = datetime.datetime.now(datetime.timezone.utc)
    payload = {
        "sub": str(user["id"]),
        "email": str(user["email"]),
        "role": role,
        "iat": now,
        "exp": now + datetime.timedelta(hours=12),
    }
    return jwt.encode(payload, _jwt_secret(), algorithm="HS256")


def decode_token(token: str) -> dict:
    """
    Decode and verify a JWT.  Raises jwt.PyJWTError on failure.
    Returns the payload dict.
    """
    return jwt.decode(token, _jwt_secret(), algorithms=["HS256"])


def _extract_token() -> str | None:
    """Pull the Bearer token from the Authorization header."""
    auth = request.headers.get("Authorization", "")
    if auth.startswith("Bearer "):
        return auth[7:].strip()
    # Also accept from X-Session-Token header (SPA convenience)
    return request.headers.get("X-Session-Token", "").strip() or None


# ---------------------------------------------------------------------------
# Request-scoped current user (stored in Flask g)
# ---------------------------------------------------------------------------
def get_current_user() -> dict | None:
    """Return the decoded token payload or None if not authenticated."""
    if hasattr(g, "_rbac_user"):
        return g._rbac_user
    token = _extract_token()
    if not token:
        g._rbac_user = None
        return None
    try:
        payload = decode_token(token)
        # Normalise role in case old tokens used an alias
        payload["role"] = _normalise_role(payload.get("role", "student"))
        g._rbac_user = payload
        return payload
    except jwt.ExpiredSignatureError:
        g._rbac_user = None
        return None
    except jwt.PyJWTError:
        g._rbac_user = None
        return None


def has_permission(role: str, permission: str) -> bool:
    r = _normalise_role(role)
    return permission in PERMISSIONS.get(r, frozenset())


# ---------------------------------------------------------------------------
# Decorators
# ---------------------------------------------------------------------------
def login_required(f):
    @functools.wraps(f)
    def wrapper(*args, **kwargs):
        user = get_current_user()
        if not user:
            return jsonify({"error": "Authentication required"}), 401
        return f(*args, **kwargs)
    return wrapper


def role_required(*roles):
    """
    Usage: @role_required("administrator")
           @role_required("administrator", "organizer")
    """
    allowed = {_normalise_role(r) for r in roles}

    def decorator(f):
        @functools.wraps(f)
        @login_required
        def wrapper(*args, **kwargs):
            user = get_current_user()
            if _normalise_role(user.get("role", "")) not in allowed:
                return jsonify({"error": "Forbidden: insufficient role"}), 403
            return f(*args, **kwargs)
        return wrapper
    return decorator


def permission_required(permission: str):
    """
    Usage: @permission_required("events:write")
    """
    def decorator(f):
        @functools.wraps(f)
        @login_required
        def wrapper(*args, **kwargs):
            user = get_current_user()
            if not has_permission(user.get("role", ""), permission):
                return jsonify({"error": f"Forbidden: missing permission '{permission}'"}), 403
            return f(*args, **kwargs)
        return wrapper
    return decorator


# ---------------------------------------------------------------------------
# Audit log helper (writes to Supabase audit_logs table, best-effort)
# ---------------------------------------------------------------------------
def audit_log(db_client: Any, actor_id: str, action: str, target: str = "", meta: dict | None = None):
    """Write a row to audit_logs.  Never raises — logging must not break requests."""
    try:
        db_client.table("audit_logs").insert({
            "actor_id": actor_id,
            "action": action,
            "target": target,
            "meta": meta or {},
        }).execute()
    except Exception:
        pass  # Best-effort; never surface to caller
